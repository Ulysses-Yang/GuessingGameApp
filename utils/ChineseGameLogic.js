const COMMON_CHARS = '天地人心口日月山水火木金土石風花雪月二雨魚鳥書馬門手足目耳口鼻耐'.split('');
export function getRandomIdiom() {
  const randomIndex = Math.floor(Math.random() * IDIOMS.length);
  return IDIOMS[randomIndex];
}

const allIdiomChars = Array.from(
  new Set(IDIOMS.flatMap(idiom => idiom.word.split('')))
);

const ALL_POSSIBLE_CHARS = [...new Set([...COMMON_CHARS, ...allIdiomChars])];

export function generateCharacterPool(answer, poolSize = 40) {
  const chars = new Set(answer.split('')); // 答案的四個字

  // 加入干擾字直到滿足 poolSize
  while (chars.size < poolSize) {
    const rand = ALL_POSSIBLE_CHARS[Math.floor(Math.random() * ALL_POSSIBLE_CHARS.length)];
    chars.add(rand);
  }

  // 打亂順序
  return shuffleArray([...chars]);
}

function shuffleArray(array) {
  return array.sort(() => Math.random() - 0.5);
}


export function checkIdiomGuess(guess, answer) {
  const result = Array(4).fill('absent');
  const answerChars = answer.split('');
  const guessChars = guess.split('');

  // 第一輪：位置對
  guessChars.forEach((char, i) => {
    if (char === answerChars[i]) {
      result[i] = 'correct';
      answerChars[i] = null;
      guessChars[i] = null;
    }
  });

  // 第二輪：字對但位置錯
  guessChars.forEach((char, i) => {
    if (char && answerChars.includes(char)) {
      result[i] = 'present';
      const idx = answerChars.indexOf(char);
      answerChars[idx] = null;
    }
  });

  return result;
}
